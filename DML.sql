-- MAKERS
SELECT CONCAT(TRIM(M.FNAME), ' ', TRIM(M.LNAME)) AS NAME, M.HANDLE, M.EMAIL, M.PHONE
FROM MAKERS AS M;

-- RECIPIENTS
SELECT CONCAT(TRIM(R.FNAME), ' ', TRIM(R.LNAME)) AS NAME, R.HANDLE, R.EMAIL, R.PHONE
FROM RECIPIENTS AS R;

-- COLORS
SELECT * FROM COLORS;

-- FLOWERS
SELECT F.FLOWER_ID, F.NAME, F.MEANING, C.COLOR FROM FLOWERS AS F
LEFT JOIN COLORS AS C
    ON C.COLOR_ID = F.COLOR_ID;

INSERT INTO FLOWERS (NAME, MEANING, COLOR_ID)
VALUES (in_flower_name, in_flower_meaning, in_color_id );

UPDATE FLOWERS AS F
SET F.NAME=in_flower_name, F.MEANING=in_flower_meaning, F.COLOR_ID = in_color_id
WHERE F.FLOWER_ID=in_flower_id;

DELETE FROM `FLOWERS` WHERE FLOWER_ID = in_flower_id;

-- FLOWERS_BOUQUETS
SELECT CONCAT(TRIM(C.COLOR), ' ', TRIM(F.NAME)) AS FLOWER,
    FB.FLOWER_ID, B.BOUQUET_ID, B.NAME AS BOUQUET
FROM FLOWERS_BOUQUETS AS FB
    LEFT JOIN BOUQUETS AS B ON FB.BOUQUET_ID = B.BOUQUET_ID
    LEFT JOIN FLOWERS AS F ON FB.FLOWER_ID = F.FLOWER_ID
    LEFT JOIN COLORS AS C ON C.COLOR_ID = F.COLOR_ID
ORDER BY B.BOUQUET_ID;
