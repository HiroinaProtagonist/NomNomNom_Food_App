-- BOUQUETS
SELECT B.BOUQUET_ID, B.NAME AS BOUQUET, B.DESCRIPTION,
    CONCAT(TRIM(M.FNAME), ' ', TRIM(M.LNAME)) AS MAKER,
    CONCAT(TRIM(R.FNAME), ' ', TRIM(R.LNAME)) AS RECIPIENT
FROM BOUQUETS AS B
    LEFT JOIN FLOWERS_BOUQUETS AS FB ON FB.BOUQUET_ID = B.BOUQUET_ID
    LEFT JOIN FLOWERS AS F ON FB.FLOWER_ID = F.FLOWER_ID
    LEFT JOIN MAKERS AS M ON M.MAKER_ID = B.MAKER_ID
    LEFT JOIN RECIPIENTS AS R ON R.RECIPIENT_ID = B.RECIPIENT_ID
ORDER BY B.BOUQUET_ID;



INSERT INTO BOUQUETS (NAME, DESCRIPTION, MAKER_ID, RECIPIENT_ID)
VALUES (in_bouquet_name, in_bouquet_description,
    in_maker_id, in_recipient_id );

UPDATE BOUQUETS AS B
SET B.NAME=in_bouquet_name, B.DESCRIPTION=in_bouquet_description,
    B.MAKER_ID=in_maker_id, B.RECIPIENT_ID=in_recipient_id
WHERE B.BOUQUET_ID=in_bouquet_id;

DELETE FROM BOUQUETS WHERE BOUQUET_ID = in_bouquet_id;